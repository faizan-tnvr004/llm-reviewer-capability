"""Frozen prompts for the code (LiveCodeBench) extension.

IMPORTANT: These prompts are frozen before the main run.  Do NOT edit them
after the pre-registration commit.  The prompts_hash() function produces a
SHA-256 over the full bundle; the hash is recorded in the analysis plan and
any post-commit edit will change it.
"""

import hashlib

# ---------------------------------------------------------------------------
# Executor instruction — appended to every problem statement
# ---------------------------------------------------------------------------

CODE_ANSWER_INSTRUCTION = (
    "\n\nWrite a complete Python 3 program that reads the input from standard input and "
    "prints the answer to standard output, exactly in the format the problem requires.\n"
    "You may reason first. End your response with the full program in a single "
    "```python code block. Do not print anything other than the required output."
)

# ---------------------------------------------------------------------------
# Reviewer prompt (C1, C2, C3) — model-based review, no test execution
# ---------------------------------------------------------------------------

CODE_REVIEW_PROMPT = """You are a code reviewer. Below is a programming problem and a proposed Python 3 solution. Your job is to judge whether the program is CORRECT: it must print the right output for every valid input within the problem's constraints and run within the time limit.

PROBLEM:
{problem}

PROPOSED PROGRAM:
```python
{solution}
```

Check the logic, edge cases and complexity. You cannot run the code. Respond in exactly this format:
VERDICT: ACCEPT
or
VERDICT: REJECT
CRITIQUE: <one short paragraph naming the specific error>

Only reject if you believe the program is incorrect or too slow. Do not reject for style. Be concise."""

# ---------------------------------------------------------------------------
# Revision prompt — sent to the executor on REJECT
# ---------------------------------------------------------------------------

CODE_REVISE_PROMPT = """You previously wrote a program for this problem:

PROBLEM:
{problem}

YOUR PROGRAM:
```python
{solution}
```

A reviewer examined your program and rejected it with this critique:
CRITIQUE: {critique}

Reconsider the problem in light of the critique. If the critique identifies a real error, fix it. If you believe your original program was correct, you may keep it. End your response with the full program in a single ```python code block."""

# ---------------------------------------------------------------------------
# C4 critique templates — generated by the public-test runner, not an LLM
# Fields are capped at 1000 characters and end with "[truncated]" if cut.
# ---------------------------------------------------------------------------

C4_FAIL_TEMPLATE = """The program failed a sample test from the problem statement.
INPUT:
{input}
EXPECTED OUTPUT:
{expected}
YOUR OUTPUT:
{actual}"""

C4_CRASH_TEMPLATE = """The program crashed on a sample test from the problem statement.
INPUT:
{input}
ERROR (last lines):
{stderr_tail}"""

C4_TIMEOUT_TEMPLATE = """The program exceeded the time limit on a sample test from the problem statement.
INPUT:
{input}"""

C4_NO_PROGRAM_TEMPLATE = "No complete Python program was found in your response."


# ---------------------------------------------------------------------------
# Hash — SHA-256 of all prompts, recorded in the analysis plan
# ---------------------------------------------------------------------------

def prompts_hash() -> str:
    """Deterministic hash of the full prompt bundle for pre-registration."""
    bundle = (
        CODE_ANSWER_INSTRUCTION + "\n---\n" +
        CODE_REVIEW_PROMPT + "\n---\n" +
        CODE_REVISE_PROMPT + "\n---\n" +
        C4_FAIL_TEMPLATE + "\n---\n" +
        C4_CRASH_TEMPLATE + "\n---\n" +
        C4_TIMEOUT_TEMPLATE + "\n---\n" +
        C4_NO_PROGRAM_TEMPLATE
    )
    return hashlib.sha256(bundle.encode("utf-8")).hexdigest()
